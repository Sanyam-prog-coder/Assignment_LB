int Fact(int iNO)
{
    if(iNO <= 1)
    {
        return 1;
    }
    else
    {
        return iNO * Fact(iNO -1);
    }
}
int main()
{
    int iValue = 0, iRet = 0;

    printf("Enter Number : ");
    scanf("%d",&iValue);

    iRet = Fact(iValue);

    printf("Factorial is : %d", iRet);

    return 0;
}
