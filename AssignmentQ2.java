class Logic
{
    void PrintReverce(int N)
    {
        int i = N;

        for(i = N; i >= 1; i--)
        {
            System.out.println(i + "");
        }
        System.out.println();
    }
}
class AssignmentQ2
{
    public static void main(String A[])
    {
        Logic sobj = new Logic();
        sobj.PrintReverce(10);
    }
}
